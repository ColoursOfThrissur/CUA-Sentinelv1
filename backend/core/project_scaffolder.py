    def _build_domain_requirements(self, description: str, tech_stack: str) -> List[str]:
        """
        Parses description + tech_stack keywords and returns a deduplicated
        pip requirements list with the right domain-specific packages.
        """
        text = (description + " " + tech_stack).lower()
        collected: Dict[str, str] = {}

        for keyword, deps in DOMAIN_DEPS.items():
            if keyword in text:
                for dep in deps:
                    pkg_name = dep.split("[")[0].split(">=")[0].split("==")[0].strip().lower()
                    if pkg_name not in collected:
                        collected[pkg_name] = dep

        all_deps = list(BASE_DEPS)
        for dep in collected.values():
            pkg_name = dep.split("[")[0].split(">=")[0].split("==")[0].strip().lower()
            if not any(pkg_name in base.lower() for base in BASE_DEPS):
                all_deps.append(dep)

        return all_deps

