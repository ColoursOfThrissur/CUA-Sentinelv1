    def _parse_blueprint_overrides(self, blueprint_content: str, ui_style: str) -> Dict[str, Any]:
        """
        Calls UIUXProMaxEngine.parse_blueprint_style_overrides() to extract
        any explicit UI/style declarations from the user's blueprint spec.
        """
        try:
            overrides = ui_ux_pro_max.parse_blueprint_style_overrides(blueprint_content, ui_style)
            return overrides
        except Exception as e:
            logger.warning(f"Blueprint style override parsing failed: {e}")
            return {
                'detected_theme': ui_style,
                'overrides_applied': [],
                'layout_hints': {},
                'framework_hints': {},
            }

